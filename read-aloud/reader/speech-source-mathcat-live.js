// ======================================================================
// speech-source-mathcat-live.js: the speech source of "MathCat TTS".
// MathCAT travels in the page (English rules only, compiled to WebAssembly, in the block
// "MathCAT engine data") and works out each formula's speech, with bookmarks for highlighting,
// when someone first presses "Read aloud" or explores a formula; exploring asks MathCAT live.
//   createSpeechSource(ctx) -> { settings, start, prepareAll, findFormulas, describe, enterFormula,
//                                navigate, applySetting, debug }
// ctx = { state, log, setStatus, pageLang, P } from reader-core.js.
// ======================================================================

// ---------------------------------------------------------------- MathCAT loader
// Generated by wasm-bindgen 0.2.128 (MIT/Apache-2.0); unchanged except that its
// exports are collected into one object.
const MathCAT = (() => {
/*@@GLUE@@*/
  return { load: __wbg_init, setRulesDir: init, version, setMathML, getSpokenText, setPreference,
           doNavigateCommand, getNavigationMathMLId };
})();

/*@@STRUCTURE-MARKS@@ (read-aloud/structure-marks.js, spliced in when the block is put together) */

function createSpeechSource(ctx) {
  const { state, log, setStatus, pageLang, P } = ctx;
  const MATHCAT_LANGUAGES = ['en'];                    // this build carries English speech rules only
  const mathLang = MATHCAT_LANGUAGES.includes(pageLang.split('-')[0]) ? pageLang.split('-')[0] : 'en';

  // MathCAT settings: the MathCAT NVDA add-on 0.7.7's defaults with Verbosity = Verbose (as in the
  // platform's proofing tool; Nicholas, 2026-11-10), plus bookmarks for highlighting, and capital
  // letters said as a word because a pitch change can't be kept when a formula is spoken as one piece.
  const MATHCAT_PREFS = [
    ['TTS', 'SSML'], ['Bookmark', 'true'],
    ['Impairment', 'Blindness'], ['Language', mathLang], ['Verbosity', 'Verbose'],
    ['MathRate', '100'], ['PauseFactor', '100'], ['SpeechSound', 'None'],
    ['SpeechStyle', 'ClearSpeak'], ['SubjectArea', 'General'], ['Chemistry', 'SpellOut'],
    ['NavMode', 'Enhanced'], ['ResetNavMode', 'false'], ['Overview', 'false'],
    ['ResetOverview', 'true'], ['NavVerbosity', 'Medium'], ['AutoZoomOut', 'true'],
    ['IgnoreBold', 'false'], ['CapitalLetters_Beep', 'false'], ['CapitalLetters_UseWord', 'true'], ['CapitalLetters_Pitch', '0']
  ];
  // Settings a student can change (the interface shows them; reader.changeSourceSetting applies them).
  const settings = [
    { key: 'style', id: 'mathstyle', label: 'Math wording', pref: 'SpeechStyle', value: 'ClearSpeak',
      options: [['ClearSpeak', 'ClearSpeak'], ['SimpleSpeak', 'SimpleSpeak']] },
    { key: 'pauses', id: 'pauses', label: 'Pauses in math', pref: 'PauseFactor', value: '100',
      options: [['100', 'Normal'], ['50', 'Shorter'], ['0', 'None']] }
  ];

  // ---------------------------------------------------------------- MathCAT (started on first use)
  async function start() {
    try {
      setStatus('Starting the math reader…');
      if (typeof WebAssembly !== 'object') throw new Error('This browser cannot run WebAssembly.');
      if (typeof DecompressionStream !== 'function') throw new Error('This browser is too old to unpack the math reader. Use a current Chrome, Edge, Firefox or Safari.');
      const t = performance.now();
      const b64 = document.getElementById(P + '-mathcat-wasm').textContent.replace(/\s+/g, '');   // the data is wrapped into lines
      const gz = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
      const stream = new Blob([gz]).stream().pipeThrough(new DecompressionStream('gzip'));
      const raw = new Uint8Array(await new Response(stream).arrayBuffer());
      await MathCAT.load({ module_or_path: raw });
      MathCAT.setRulesDir();
      for (const [k, v] of MATHCAT_PREFS) MathCAT.setPreference(k, v);
      for (const s of settings) MathCAT.setPreference(s.pref, s.value);
      log('MathCAT ' + MathCAT.version() + ' started in ' + Math.round(performance.now() - t) + ' ms (language ' + mathLang + ')');
      prepareAll();
      return true;
    } catch (e) {
      setStatus('The math reader could not start: ' + e.message + ' Text will still be read; formulas will be skipped.', true);
      log('error: ' + e.message);
      return false;
    }
  }
  const applySetting = (s) => MathCAT.setPreference(s.pref, s.value);

  // Every MathML element carries a data-atc-id label, and MathCAT gets a copy with those labels as
  // ids. MathJax copied the labels onto the parts it drew, so a bookmark's id finds the drawn
  // part. MathCAT also returns a tidied copy with some groupings of its own; those are mapped to
  // the labelled parts inside them.
  function buildIdMap(f, canonical) {
    const doc = new DOMParser().parseFromString(canonical, 'application/xml');
    const map = new Map();
    const onPage = (id) => {
      if (!id) return [];
      const sel = '[data-atc-id="' + CSS.escape(id) + '"]';
      // Drawn by MathJax (HTML or SVG): only the drawn parts (the hidden MathML copy carries the same labels).
      if (state.draw === 'mathjax') return Array.from(f.el.querySelectorAll(':scope > mjx-math ' + sel + ', :scope > svg ' + sel));
      return [...(f.drawRoot.matches(sel) ? [f.drawRoot] : []), ...f.drawRoot.querySelectorAll(sel)];
    };
    const resolve = (node) => {
      const els = onPage(node.getAttribute('id'));
      if (els.length) return els;
      return Array.from(node.children).flatMap(resolve);
    };
    for (const node of doc.querySelectorAll('[id]')) map.set(node.getAttribute('id'), resolve(node));
    const root = doc.documentElement;                     // the whole expression = the whole formula
    map.set(root.getAttribute('id'), [f.el]);
    if (root.children.length === 1) map.set(root.children[0].getAttribute('id'), [f.el]);
    return map;
  }

  // MathCAT's SSML as one stretch of plain text, the way MathCAT's own plain-text mode does it:
  // a pause becomes "," (up to 250 ms) or ";" (longer), and the letter "a" becomes "eigh".
  // Bookmarks are kept as positions in the text.
  function ssmlToSpeech(ssml) {
    const doc = new DOMParser().parseFromString('<speak>' + ssml + '</speak>', 'application/xml');
    if (doc.getElementsByTagName('parsererror').length) {
      return { text: ssml.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim(), marks: [] };
    }
    let text = '';
    const marks = [];
    const addWords = (t) => {
      t = t.replace(/\s+/g, ' ').trim();
      if (!t) return;
      if (text && !/\s$/.test(text)) text += ' ';
      text += t;
    };
    const addPause = (ms) => {
      if (ms <= 50) return;
      text = text.replace(/\s+$/, '');
      if (!text) return;
      const p = ms <= 250 ? ',' : ';';
      if (/[,;]$/.test(text)) { if (p === ';') text = text.slice(0, -1) + ';'; } else text += p;
      marks.push({ at: text.length, id: null });          // a pause usually starts a new phrase
    };
    (function walk(nodes) {
      for (const n of nodes) {
        // MathCAT sometimes leaves its internal "[[" navigation marker in table-cell speech.
        if (n.nodeType === Node.TEXT_NODE) { addWords(n.data.replace(/\[\[|\]\]/g, ' ')); continue; }
        if (n.nodeType !== Node.ELEMENT_NODE) continue;
        const tag = n.localName;
        if (tag === 'mark') marks.push({ at: text.length, id: n.getAttribute('name') });
        else if (tag === 'break') {
          const t = n.getAttribute('time') || '';
          addPause(/ms$/.test(t) ? parseFloat(t) : parseFloat(t) * 1000 || 0);
        } else if (tag === 'say-as') {
          const t = n.textContent.trim();
          addWords(/^a$/i.test(t) && mathLang === 'en' ? 'eigh' : t);
        } else if (tag === 'audio') continue;
        else walk(n.childNodes);
      }
    })(doc.documentElement.childNodes);
    text = text.replace(/[\s,;]+$/, '');
    return { text, marks: marks.filter((m) => m.at < text.length || m.id === null) };
  }

  function prepareFormula(f) {
    const canonical = MathCAT.setMathML(f.source);
    f.idMap = buildIdMap(f, canonical);
    const speech = ssmlToSpeech(MathCAT.getSpokenText());
    f.text = speech.text;
    const marks = addStructureMarks(speech.text, speech.marks, new DOMParser().parseFromString(canonical, 'application/xml'));
    f.marks = marks.filter((m) => m.id === null || (f.idMap.get(m.id) || []).length);
  }
  function prepareAll() {
    const t = performance.now();
    let failed = 0;
    for (const f of state.formulas) {
      try { prepareFormula(f); }
      catch (e) { failed++; f.text = ''; f.marks = []; f.idMap = new Map(); log('MathCAT could not read formula ' + (f.n + 1) + ': ' + String(e).split('\n')[0]); }
    }
    log('speech for ' + state.formulas.length + ' formulas in ' + Math.round(performance.now() - t) + ' ms' + (failed ? ' (' + failed + ' failed)' : ''));
    if (failed) setStatus('MathCAT could not read ' + failed + ' formula(s); they will be skipped. See the read-aloud log at the end of the page.', true);
  }

  // ---------------------------------------------------------------- exploring
  // MathCAT holds one formula at a time; loading it also puts exploring back at the start.
  const enterFormula = (f) => prepareFormula(f);
  function navigate(f, command) {
    let ssml, id;
    try {
      ssml = MathCAT.doNavigateCommand(command);
      [id] = MathCAT.getNavigationMathMLId();
    } catch (e) {
      // MathCAT 0.7.7 can land on a position it then can't move from (the whole formula with offset 1,
      // after ZoomOutAll from some places), so every key would fail from there. Start the formula over,
      // as if it had just been entered; the Pregen version does the same.
      prepareFormula(f);
      return { restart: true, log: 'navigation error: ' + String(e).split('\n')[0] + ' (formula restarted)' };
    }
    const text = ssmlToSpeech(ssml).text;
    return { text, part: id, log: 'nav ' + command + ' -> ' + id + ': "' + text + '"' };
  }

  // ---------------------------------------------------------------- finding the formulas
  // Pages drawn in advance carry MathJax's drawing with the labelled MathML in each formula's
  // hidden copy. Otherwise label the page's own MathML, which the browser draws.
  const allIn = (root) => [root, ...root.querySelectorAll('*')];
  function mathcatSource(math) {
    const copy = math.cloneNode(true);
    copy.removeAttribute('data-atc-formula');
    for (const el of allIn(copy)) { el.setAttribute('id', el.getAttribute('data-atc-id')); el.removeAttribute('data-atc-id'); }
    return new XMLSerializer().serializeToString(copy);
  }
  function findFormulas() {
    // One entry per formula. (MathJax may split a long inline formula into several pieces.)
    const pre = Array.from(document.querySelectorAll('mjx-container'))
      .filter((c) => c.querySelector(':scope > mjx-math, :scope > svg'))
      .map((c) => ({ el: c, drawRoot: c, hidden: c.querySelector('mjx-assistive-mml > math[data-atc-formula]') }))
      .filter((x) => x.hidden && !x.el.closest('[data-atc-rd-skip]'));
    if (pre.length) {
      state.draw = 'mathjax';
      return pre.map(({ el, drawRoot, hidden }) => ({ el, drawRoot, n: parseInt(hidden.getAttribute('data-atc-formula'), 10), source: mathcatSource(hidden) }));
    }
    const maths = Array.from(document.querySelectorAll('math')).filter((m) => !m.closest('[data-atc-rd-skip], mjx-assistive-mml'));
    state.draw = maths.length ? 'native' : 'none';
    return maths.map((m, n) => {
      allIn(m).forEach((el, k) => el.setAttribute('data-atc-id', 'f' + n + '-' + k));
      m.setAttribute('data-atc-formula', String(n));
      return { el: m, drawRoot: m, n, source: mathcatSource(m) };
    });
  }
  const describe = () => state.draw === 'mathjax'
    ? 'MathJax, in advance (' + (document.querySelector('mjx-container > svg') ? 'SVG' : 'HTML with MathJax fonts') + ')'
    : state.draw === 'native' ? 'the browser (plain MathML)' : 'no formulas';

  return { settings, start, prepareAll, findFormulas, describe, enterFormula, navigate, applySetting,
           debug: { ssmlToSpeech, MathCAT } };
}
