  // >>> SRE INTENT TRANSLATOR START (extracted by js/test-sre-intent.mjs)
  //  translateIntents(root): for each element under (and including) root that
  //  has an `intent`, either writes the ext-* carriers the rules above read,
  //  or leaves the element alone so SRE reads it as usual. Returns one log
  //  entry per intent: { intent, result: 'translated' | reason, words }.
  //  Uses only getAttribute / setAttribute / hasAttribute / removeAttribute /
  //  childNodes / getElementsByTagName, so the same code runs on the page's
  //  DOM and on @xmldom/xmldom in the Node test.
  var SLOT_LETTERS = 'abcdef';          // the rules cover up to six operands
  var CARRIERS = ['ext-arity', 'ext-open', 'ext-close',
    'ext-mid1', 'ext-mid2', 'ext-mid3', 'ext-mid4', 'ext-mid5'];

  // Reads a MathML 4 intent value just far enough: a head (concept name or
  // _literal), optional :properties, optional (operands), where an operand is
  // $ref, a number, or a nested intent. Throws on anything else.
  function parseIntent(s) {
    var i = 0;
    function ws() { while (/\s/.test(s.charAt(i))) i++; }
    function term() {
      ws();
      var m;
      if (s.charAt(i) === '$') {
        i++;
        m = /^[A-Za-z][\w.-]*/.exec(s.slice(i));
        if (!m) throw 'bad reference';
        i += m[0].length;
        return { ref: m[0] };
      }
      m = /^-?\d+(\.\d+)?/.exec(s.slice(i));
      if (m) { i += m[0].length; return { num: m[0] }; }
      var head = null;
      m = /^_?[A-Za-z][\w.-]*/.exec(s.slice(i));
      if (m) { head = m[0]; i += m[0].length; }
      var props = [];
      while (s.charAt(i) === ':') {
        i++;
        var p = /^[A-Za-z][\w-]*/.exec(s.slice(i));
        if (!p) throw 'bad property';
        props.push(p[0]);
        i += p[0].length;
      }
      if (!head && !props.length) throw 'no name';
      var args = null;
      ws();
      if (s.charAt(i) === '(') {
        i++;
        args = [];
        ws();
        if (s.charAt(i) !== ')') {
          for (;;) {
            args.push(term());
            ws();
            if (s.charAt(i) === ',') { i++; continue; }
            break;
          }
        }
        if (s.charAt(i) !== ')') throw 'missing )';
        i++;
      }
      return { head: head, props: props, args: args };
    }
    var t = term();
    ws();
    if (i !== s.length) throw 'trailing text';
    return t;
  }

  function elementChildren(el) {
    var out = [], kids = el.childNodes || [];
    for (var i = 0; i < kids.length; i++) if (kids[i].nodeType === 1) out.push(kids[i]);
    return out;
  }

  // MathML 4: $name refers to a descendant with arg="name", found without
  // looking inside a descendant that has its own intent (that element itself
  // can still be the one).
  function findArg(el, name) {
    var kids = elementChildren(el);
    for (var i = 0; i < kids.length; i++) {
      if (kids[i].getAttribute('arg') === name) return kids[i];
      if (!kids[i].hasAttribute('intent')) {
        var found = findArg(kids[i], name);
        if (found) return found;
      }
    }
    return null;
  }

  // Words made from the name: drop a literal's leading "_", then hyphens,
  // underscores and dots become spaces.
  function wordsOf(head) {
    return head.replace(/^_/, '').replace(/[-_.]+/g, ' ').replace(/^\s+|\s+$/g, '');
  }

  // What to write for one element, or { skip: reason }.
  function planIntent(el) {
    if (el.hasAttribute('ext-arity')) return { skip: 'already carries ext-* carriers' };
    var t;
    try { t = parseIntent(el.getAttribute('intent')); }
    catch (e) { return { skip: 'malformed (' + e + '): left to SRE' }; }
    if (t.ref || t.num) return { skip: 'a bare reference or number: left to SRE' };
    if (!t.head) return { skip: 'property only: left to SRE' };
    var args = t.args || [];
    if (args.length > SLOT_LETTERS.length) return { skip: 'more than six operands: left to SRE' };
    var nodes = [];
    for (var k = 0; k < args.length; k++) {
      var a = args[k];
      if (a.num) return { skip: 'a number among the operands: left to SRE' };
      if (!a.ref) return { skip: 'a nested intent among the operands: left to SRE' };
      var node = findArg(el, a.ref);
      // The element itself as the only operand: the platform's converter puts
      // \MathMLintent and \MathMLarg on ONE element when the operand is the
      // whole wrapped expression (as LuaLaTeX does). Spoken by the merged
      // rule, which reads the element itself; with other operands the rules
      // could not, so that is left to SRE.
      if (!node && el.getAttribute('arg') === a.ref) {
        if (args.length > 1) return { skip: 'the element itself and other operands: left to SRE' };
        node = el;
      }
      if (!node) return { skip: 'operand $' + a.ref + ' has no matching arg: left to SRE' };
      if (nodes.indexOf(node) >= 0) return { skip: 'an operand used twice: left to SRE' };
      if (node.hasAttribute('ext-argname')) return { skip: 'an operand shared with another intent: left to SRE' };
      nodes.push(node);
    }
    var words = wordsOf(t.head);
    var n = nodes.length;
    var has = function (prop) { return t.props.indexOf(prop) >= 0; };
    var p;
    if (has('infix') && n >= 2) p = { open: '', mid: words, close: '' };
    else if (has('postfix') && n >= 1) p = { open: '', mid: 'and', close: words };
    else p = { open: n ? words + ' of' : words, mid: 'and', close: '' };
    var attrs = { 'ext-arity': String(n), 'ext-open': p.open, 'ext-close': p.close };
    for (var j = 1; j < n; j++) attrs['ext-mid' + j] = p.mid;
    return { attrs: attrs, nodes: nodes, words: words };
  }

  // The rules find operand k as the FIRST descendant (document order) whose
  // ext-argname is letter k. A nested intent's operand can come first and
  // carry the same letter; then the outer intent would speak the wrong part.
  function firstMarked(el, letter) {
    var all = el.getElementsByTagName('*');
    for (var i = 0; i < all.length; i++) {
      if (all[i].getAttribute('ext-argname') === letter) return all[i];
    }
    return null;
  }

  function translateIntents(root) {
    var log = [], done = [];
    if (!root || !root.getElementsByTagName) return log;
    var list = [root].concat(Array.prototype.slice.call(root.getElementsByTagName('*')));
    for (var i = 0; i < list.length; i++) {
      var el = list[i];
      if (!el.hasAttribute || !el.hasAttribute('intent')) continue;
      var entry = { intent: el.getAttribute('intent'), result: '', words: '' };
      log.push(entry);
      var plan = planIntent(el);
      if (plan.skip) { entry.result = plan.skip; continue; }
      for (var key in plan.attrs) el.setAttribute(key, plan.attrs[key]);
      for (var k = 0; k < plan.nodes.length; k++) {
        plan.nodes[k].setAttribute('ext-argname', SLOT_LETTERS.charAt(k));
      }
      entry.result = 'translated';
      entry.words = plan.words;
      done.push({ el: el, nodes: plan.nodes, entry: entry });
    }
    // Leave to SRE any intent whose operands the rules would not find; undoing
    // one can clear another's clash, so repeat until nothing changes.
    for (var changed = true; changed;) {
      changed = false;
      for (var d = 0; d < done.length; d++) {
        var it = done[d];
        if (it.entry.result !== 'translated') continue;
        var ok = true;
        for (var s = 0; s < it.nodes.length; s++) {
          if (it.nodes[s] === it.el) continue;    // read by the merged rule, no lookup
          if (firstMarked(it.el, SLOT_LETTERS.charAt(s)) !== it.nodes[s]) { ok = false; break; }
        }
        if (ok) continue;
        for (var c = 0; c < CARRIERS.length; c++) it.el.removeAttribute(CARRIERS[c]);
        for (var r = 0; r < it.nodes.length; r++) it.nodes[r].removeAttribute('ext-argname');
        it.entry.result = 'operand letters clash with a nested intent: left to SRE';
        it.entry.words = '';
        changed = true;
      }
    }
    return log;
  }
  // <<< SRE INTENT TRANSLATOR END

  // -------------------------------------------------------------------------
  //  mhchem PUA ARROW REMAP (Runtime A chemistry fix, 2026-08-16)
  //
  //  MathJax's mhchem draws reaction arrows from its font's Private Use Area
  //  (E408/E409/E40A/E428/E429/E42A/E42B on 4.1.3). PUA is meaningless to both
  //  accessibility channels: SRE speaks nothing (silent arrows) and MathCAT
  //  cannot recognise a chemical EQUATION without a real arrow. This map (kept
  //  in sync with mml-condition.js MHCHEM_ARROW_MAP in the platform — a golden
  //  test asserts the sync) remaps to the nearest standard character. The two
  //  biased equilibria genuinely have no Unicode form; U+21CC is the accepted
  //  stand-in. Idempotent, and a no-op if a future MathJax stops using PUA.
  //
  //  WHERE it applies — accessibility serializations ONLY, never the visual
  //  tree. MathJax round-trips the render tree through the same serializer
  //  during enrichment (enrich() recompiles serialized MathML into this.root),
  //  so patching the serializer would leak the substitute character into the
  //  RENDERED mo — whose glyph comes from the mhchem PUA font variant
  //  (data-mjx-variant="-mhchem") and whose stretchy/labeled-arrow layout
  //  depends on it. Instead:
  //    (a) SRE channel: the payload posted to the speech worker (postMessage
  //        wrap, installed by installWorkerPatch in every delivery mode);
  //    (b) MathCAT channel: the hidden <mjx-assistive-mml> DOM, via a
  //        renderAction at priority 190 (after ASSISTIVEMML=153, before
  //        INSERTED=200) so it re-runs on every rerender/menu-mode switch.
  //  Verified 2026-08-16 (Node probe, 4.1.3 + SRE 5.0.0-rc.4): remapping the
  //  ALREADY-ENRICHED payload still unlocks the spoken arrow — annotations
  //  computed on the PUA character do not block it.
  // -------------------------------------------------------------------------
  var CHEM_ARROW_MAP = {
    0xE428: 0x27F5, // ⟵  \mhchemlongleftarrow
    0xE429: 0x27F6, // ⟶  \mhchemlongrightarrow
    0xE42A: 0x27F7, // ⟷  \mhchemlongleftrightarrow
    0xE42B: 0x21C4, // ⇄  \mhchemlongleftrightarrows
    0xE408: 0x21CC, // ⇌  \mhchemlongrightleftharpoons (equilibrium)
    0xE409: 0x21CC, // ⇌  \mhchemlongRightleftharpoons (biased; approximated)
    0xE40A: 0x21CC  // ⇌  \mhchemlongLeftrightharpoons (biased; approximated)
  };

  // A PUA character in either serialized form: numeric char reference
  // (&#xE429; — what SerializedMmlVisitor emits) or the literal codepoint.
  var PUA_TOKEN = /&#x([eEfF][0-9A-Fa-f]{3});|([\uE000-\uF8FF])/g;

  // String form, for the worker payload (parsed as XML, so entity output).
  function remapChemArrows(str) {
    return String(str).replace(PUA_TOKEN, function (whole, hex, lit) {
      var cp = hex ? parseInt(hex, 16) : lit.charCodeAt(0);
      var target = CHEM_ARROW_MAP[cp];
      return target == null ? whole
        : '&#x' + target.toString(16).toUpperCase() + ';';
    });
  }

  // -------------------------------------------------------------------------
  //  CHEM SHIM — mhchem noise removal, SRE PAYLOAD ONLY (2026-08-30)
  //
  //  SRE has no chemistry model. mhchem's output collides with three of its
  //  heuristics, verified by probe against the golden speech path:
  //    (a) UNIT GUESS. ClearSpeak's 'unit' annotator marks every implicit
  //        multiplication as a possible unit, and then speaks UPRIGHT single
  //        letters from the units dictionary: \ce{N2} -> "Newtons sub 2",
  //        \ce{5m} -> "meters". Every element symbol is upright, so this fires
  //        on essentially all chemistry. Fix: drop mathvariant="normal" from
  //        <mi> inside chemistry payloads only.
  //    (b) EMPTY NODES. mhchem pads a $...$ math escape with ~ spaces; those
  //        serialize as whitespace-only <mtext> and are VOICED as "empty" when
  //        an intent-wrapped relation restructures the parse ("... empty is in
  //        equilibrium with empty ..."). Fix: drop whitespace-only <mtext>.
  //    (c) FUNCTION GUESS. mhchem hangs scripts off a zero-width \vphantom{A}
  //        instead of the element, and SRE reads the orphaned letter as an
  //        applied function ("normal H OF sub 2"). Fix: re-attach the script to
  //        the preceding element. This one is STRUCTURAL, so it runs behind
  //        balanceOk() and is discarded whole if tag counts do not match --
  //        a malformed payload would kill speech for the whole expression.
  //
  //  WHERE: the worker payload only (see wrapWorkerPostMessage). Never the
  //  rendered tree, never the assistive MathML MathCAT reads, never the
  //  document. MathCAT infers chemistry natively and must not be touched.
  //
  //  GATE: mhchem fingerprints. \ce in data-latex when present, the -mhchem
  //  font variant on arrows, or the zero-width phantom construction. Genuine
  //  units written OUTSIDE \ce (5 m + 3 kg) match none of these and keep their
  //  unit speech -- there is a control fixture asserting exactly that.
  // -------------------------------------------------------------------------
  // >>> CHEM SHIM START (extracted verbatim by test/_probe-chemshim-unit.mjs)
  //  v2 (2026-08-30, after live NVDA test of v1 showed NO effect).
  //  WHAT THE LIVE CHANNEL ACTUALLY IS: MathJax enriches first and posts
  //  ENRICHED MathML (item.outputData.mml) to the speech worker, which calls
  //  SRE.worker.speech(mml, opts); the spoken string is result.label. On that
  //  path SRE reads the semantic attributes, NOT the presentation markup —
  //  so v1's mathvariant strip and phantom-restructure were inert. Verified
  //  by test/_probe-worker-truth2.mjs, which reproduces the live strings.
  //  THE TWO LEVERS THAT WORK LIVE:
  //    (a) data-semantic-font="normal" -> drives the units dictionary
  //        ("Newtons", "normal H"). Removing it inside chemistry restores
  //        plain letters. NOTE: this is why the gate matters — removing it
  //        from a genuine unit expression would turn "5 meters" into "5 m".
  //    (b) whitespace-only <mtext> -> mhchem's ~ padding around a $...$
  //        escape, voiced as "empty" once an intent-wrapped relation
  //        restructures the parse.
  //  Not fixed here: anything requiring pre-enrichment changes.
  //  v3 adds (c): the "of" adjacency guess. Enrichment decides an element
  //  letter is a FUNCTION APPLIED to what follows (H2O -> "H of sub 2 O"),
  //  marking type=appl + role="simple function" and INSERTING an invisible
  //  function-application <mo>. Probe test/_probe-of-residue.mjs: no single
  //  edit clears it — all three must go together. Inside chemistry a function
  //  application is never legitimate, so this is safe behind the gate.
  var CHEM_FINGERPRINT = /\\ce\{|data-mjx-variant="-mhchem"|<mpadded[^>]*width="0"[^>]*>\s*<mphantom/;
  var SEM_FONT_NORMAL = /\s*data-semantic-font="normal"/g;
  var BLANK_MTEXT     = /<mtext\b[^>]*>(?:\s|&#xA0;|&#xa0;|&nbsp;|\u00A0)*<\/mtext>/g;
  var APPL_MO         = /<mo\b[^>]*data-semantic-role="application"[^>]*>[\s\S]*?<\/mo>/g;
  var ROLE_SIMPLEFUNC = /data-semantic-role="simple function"/g;
  var TYPE_APPL       = /data-semantic-type="appl"/g;

  function chemShim(str) {
    try {
      var s = String(str);
      if (!CHEM_FINGERPRINT.test(s)) return str;      // not chemistry: untouched
      s = s.replace(SEM_FONT_NORMAL, '');             // (a) unit / "normal" guess
      s = s.replace(BLANK_MTEXT, '');                 // (b) "empty" nodes
      s = s.replace(ROLE_SIMPLEFUNC, 'data-semantic-role="latinletter"')
           .replace(TYPE_APPL, 'data-semantic-type="infixop"')
           .replace(APPL_MO, '');                     // (c) "of" function guess
      return s;
    } catch (e) {
      return str;                                     // never break the channel
    }
  }
  // <<< CHEM SHIM END

  // DOM form, for parsed text nodes (literal characters in, literal out).
  var LITERAL_PUA = /[\uE000-\uF8FF]/g;
  function remapChemArrowsDom(el) {
    var walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, null);
    var n;
    while ((n = walker.nextNode())) {
      var v = n.nodeValue;
      if (!v) continue;
      var w = v.replace(LITERAL_PUA, function (ch) {
        var target = CHEM_ARROW_MAP[ch.charCodeAt(0)];
        return target == null ? ch : String.fromCharCode(target);
      });
      if (w !== v) n.nodeValue = w;
    }
  }

  // renderAction bodies. Must return false (true would halt the render chain)
  // and must NEVER throw — a failure here may not break typesetting.
  function remapAssistiveMath(math) {
    try {
      var root = math && math.typesetRoot;
      if (!root || !root.querySelectorAll) return false;
      var mmls = root.querySelectorAll('mjx-assistive-mml');
      for (var i = 0; i < mmls.length; i++) remapChemArrowsDom(mmls[i]);
    } catch (e) { /* non-fatal by design */ }
    return false;
  }
  function remapAssistiveDoc(doc) {
    try {
      var iter = doc.math[Symbol.iterator]();
      for (var s = iter.next(); !s.done; s = iter.next()) {
        remapAssistiveMath(s.value);
      }
    } catch (e) { /* non-fatal by design */ }
    return false;
  }

  // Wrap a speech worker's postMessage so any MathML payload crossing into
  // the worker has its PUA arrows remapped. Only msg.data.mml is rewritten;
  // the message is shallow-copied, not mutated. Runs in EVERY delivery mode.
  function wrapWorkerPostMessage(webworker) {
    try {
      var origPost = webworker.postMessage;
      webworker.postMessage = function (msg) {
        try {
          if (msg && msg.data && typeof msg.data.mml === 'string') {
            var fixed = chemShim(remapChemArrows(msg.data.mml));
            if (fixed !== msg.data.mml) {
              msg = Object.assign({}, msg, {
                data: Object.assign({}, msg.data, { mml: fixed })
              });
            }
          }
        } catch (e) { /* pass the original message through */ }
        var args = Array.prototype.slice.call(arguments, 1);
        return origPost.apply(webworker, [msg].concat(args));
      };
    } catch (e) { /* worker stays unwrapped; arrows read as before */ }
    return webworker;
  }
  // createWorker may (in principle) return a promise; wrap either way.
  function wrapMaybeWorker(w) {
    return w && typeof w.then === 'function'
      ? w.then(wrapWorkerPostMessage)
      : wrapWorkerPostMessage(w);
  }

  // -------------------------------------------------------------------------
  //  Config mutations. This script runs before the library, so we can add to
  //  window.MathJax directly and leave the filter's own config block untouched.
  // -------------------------------------------------------------------------
  var MJ = window.MathJax = window.MathJax || {};

  // 1. composed mode needs the patched locale directory. Set it through the
  //    LOADER PATH ALIAS, not options.worker.maps: the a11y/speech component
  //    resolves [mathmaps] and then does new URL(value, location), which turns
  //    a relative path into an absolute one against the PAGE. Setting
  //    options.worker.maps instead leaves it relative, and the worker resolves
  //    it against its own URL under /sre/ — a silent 404 and no speech.
  if (RULES_DELIVERY === 'path' && MAPS_PATH) {
    var ld = MJ.loader = MJ.loader || {};
    ld.paths = ld.paths || {};
    if (!ld.paths.mathmaps) ld.paths.mathmaps = MAPS_PATH;
  }

  // 2. the assistive-MathML arrow remap runs as a renderAction so it re-fires
  //    on every render, rerender, and menu-mode switch (the hidden MathML is
  //    regenerated each time). Priority 190: after ASSISTIVEMML (153), before
  //    INSERTED (200). Functions returning false keep the render chain going.
  var opts = MJ.options = MJ.options || {};
  var ra = opts.renderActions = opts.renderActions || {};
  if (!ra.intentChemArrows) {
    ra.intentChemArrows = [190, remapAssistiveDoc, remapAssistiveMath];
  }

  // -------------------------------------------------------------------------
  //  'inline' RULES DELIVERY  (Option C)
  //
  //  The problem: SRE loads its rules from JSON locale files, and there is no
  //  way to inject rules from the page. MathJax deletes SRE's `custom` loader
  //  before the options cross into the worker (GeneratorPool.ts:
  //  `delete this._options.custom`) because a function cannot survive
  //  postMessage. Data can cross that boundary; code cannot.
  //
  //  The opening: MathJax builds the worker from a small blob script that it
  //  constructs IN THE PAGE (HTMLAdaptor.createWorker), roughly
  //      self.maps = '<url>'; importScripts('<cdn>/sre/speech-worker.js');
  //  So we can prepend our own code to that blob. Inside the worker we wrap
  //  self.fetch, let the locale request complete as normal, merge our rules
  //  into the parsed JSON in memory, and hand the combined object back.
  //
  //  Nothing is downloaded for our sake and nothing is written anywhere. The
  //  locale file was already being fetched on every page load; we only modify
  //  the result in passing. Our rules travel inside the HTML (~1 KB).
  //
  //  CAVEAT: createWorker is not a documented extension point, so a MathJax
  //  upgrade could change its shape. Pin the MathJax version. On any failure we
  //  fall back to the original method, which costs only composed speech on
  //  complex arguments — the flat channel still works.
  // -------------------------------------------------------------------------
  function installWorkerPatch() {
    var HA;
    try {
      HA = MathJax._.adaptors.HTMLAdaptor.HTMLAdaptor;
    } catch (e) { HA = null; }
    if (!HA || !HA.prototype || typeof HA.prototype.createWorker !== 'function') {
      if (window.console) console.warn('[intent] createWorker not found; rules not injected');
      return false;
    }

    // Safe to embed in <script>: JSON.stringify handles quoting; we additionally
    // neutralise "<" so a stray "</script" cannot terminate the block early.
    function embed(value) {
      return JSON.stringify(value).replace(/</g, '\\u003c');
    }

    var original = HA.prototype.createWorker;

    HA.prototype.createWorker = function (listener, options) {
      // Non-inline deliveries build no rules blob, but the chem-arrow remap
      // still applies: wrap postMessage on whatever the original creates.
      if (RULES_DELIVERY !== 'inline') {
        return wrapMaybeWorker(original.call(this, listener, options));
      }
      try {
        var file = options.path + '/' + options.worker;
        var target = '/' + RULES_LOCALE + '.json';
        var content =
          'self.maps = ' + embed(options.maps) + ';\n' +
          'self.__intentRules = ' + embed(RULES) + ';\n' +
          'self.__intentTarget = ' + embed(target) + ';\n' +
          '(function () {\n' +
          '  var origFetch = self.fetch;\n' +
          '  self.fetch = function (url) {\n' +
          '    var p = origFetch.apply(self, arguments);\n' +
          '    if (String(url).indexOf(self.__intentTarget) < 0) return p;\n' +
          '    return p.then(function (r) { return r.json(); }).then(function (j) {\n' +
          '      for (var k in self.__intentRules) j[k] = self.__intentRules[k];\n' +
          '      return { json: function () { return Promise.resolve(j); } };\n' +
          '    });\n' +
          '  };\n' +
          '})();\n' +
          'importScripts(' + embed(file) + ');\n';

        var url = URL.createObjectURL(
          new Blob([content], { type: 'text/javascript' })
        );
        var webworker = new Worker(url);
        webworker.onmessage = listener;
        URL.revokeObjectURL(url);
        wrapWorkerPostMessage(webworker);
        if (window.console) {
          console.log('[intent] worker patched; rules merged into' + target +
            '; chem arrows remapped');
        }
        return webworker;
      } catch (err) {
        if (window.console) {
          console.error('[intent] worker patch failed, using original: ' + err.message);
        }
        return wrapMaybeWorker(original.call(this, listener, options));
      }
    };
    return true;
  }

  // -------------------------------------------------------------------------
  //  SELF-TEST — replaces the old silent flat fallback.
  //
  //  Spoken intent either works or it doesn't, and a reader has no way to
  //  tell. So after typesetting we check one thing: does any expression's
  //  generated speech actually contain the words of an intent the translator
  //  handled? If not, the rules never reached SRE and every intent is being
  //  read by SRE as usual.
  //
  //  Reported three ways, none of which disturbs the page:
  //    * console.error, for support staff and automated checks
  //    * data-intent-speech="ok" | "skipped" | "degraded" on <html>, so a
  //      stylesheet can surface a visible notice if you want one, e.g.
  //        html[data-intent-speech="degraded"] body::before { content: "..." }
  //    * window.__intentStatus, for a test harness to read
  //
  //  "skipped" when the page has no intent the translator handled, and unless
  //  the active ruleset is a ClearSpeak one, since our rules are deliberately
  //  clearspeak-only and MathSpeak is expected to read verbatim.
  // -------------------------------------------------------------------------
  function selfTest() {
    function report(state, detail) {
      window.__intentStatus = {
        state: state, detail: detail, phrases: TRANSLATED.slice(), leftToSre: LEFT_TO_SRE
      };
      try { document.documentElement.setAttribute('data-intent-speech', state); } catch (e) {}
      if (!window.console) return;
      if (state === 'ok') console.log('[intent] speech self-test OK — ' + detail);
      else if (state === 'skipped') console.log('[intent] speech self-test skipped — ' + detail);
      else console.error('[intent] SPEECH DEGRADED — ' + detail +
        '\n[intent] Intents are being read by SRE as usual. ' +
        'intent/MathCAT is unaffected. Check for a blocked worker (CSP), a ' +
        'MathJax version change, or a failed rules merge.');
    }

    if (!TRANSLATED.length) {
      report('skipped', LEFT_TO_SRE
        ? LEFT_TO_SRE + ' intent(s) on this page, none of them translated (left to SRE)'
        : 'no intent on this page');
      return;
    }

    // Read the LIVE menu settings, not the static page config: MathJax merges
    // settings saved in localStorage ('MathJax-Menu-Settings') over the page
    // config at startup, so the page may not be in the mode the config baked in.
    var settings = null;
    try { settings = MathJax.startup.document.menu.settings; } catch (e) {}

    // In hidden-MathML (MathCat) mode, MathJax speech is off by design, so an
    // absence of composed speech is EXPECTED, not degradation. Without this
    // check, every load of a page last left in MathCat mode logs a false alarm.
    if (settings && (settings.assistiveMml || !settings.speech)) {
      report('skipped', 'page is in hidden-MathML (MathCat) mode — MathJax ' +
        'speech is off, so composed speech is expected to be absent. Switch ' +
        'to MathJax-speech mode and reload to test the SRE channel.');
      return;
    }

    var ruleset = '';
    try {
      ruleset = (settings && settings.speechRules) ||
        MathJax.startup.document.options.menuOptions.settings.speechRules || '';
    } catch (e) {}
    if (ruleset.indexOf('clearspeak') !== 0) {
      report('skipped', 'ruleset is "' + (ruleset || 'unknown') +
        '"; our rules are clearspeak-only by design');
      return;
    }

    var containers = document.querySelectorAll('mjx-container[data-semantic-speech-none]');
    if (!containers.length) {
      report('degraded', 'no speech was attached to any expression');
      return;
    }
    for (var i = 0; i < containers.length; i++) {
      var said = containers[i].getAttribute('data-semantic-speech-none') || '';
      for (var j = 0; j < TRANSLATED.length; j++) {
