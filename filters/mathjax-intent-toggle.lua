  //            worker already downloads. No companion folder, no extra request.
  //            Uses an internal MathJax method — see installWorkerPatch.
  //  'path'    serve a patched locale directory; point [mathmaps] at MAPS_PATH.
  //  'none'    deliver no rules; intents are read by SRE as usual.
  var RULES_DELIVERY = '__RULES_DELIVERY__';
  var MAPS_PATH      = '__MAPS_PATH__';   // only when RULES_DELIVERY = 'path'

  // Words of every intent the translator handled on this page, and how many
  // intents it left to SRE. Used by selfTest() to tell "spoken" from
  // "silently degraded".
  var TRANSLATED = [];
  var LEFT_TO_SRE = 0;

  // >>> SRE INTENT RULES START (extracted by js/test-sre-intent.mjs)
  //  The parked ClearSpeak rules (2026-08), kept as they were, plus the
  //  merged-operand fix of 2026-11-01. One rule per number of operands (0-6):
  //  the opening words, each operand, the middle words between operands, the
  //  closing words. Rules key on the carriers the translator writes:
  //    ext-arity           number of operands
  //    ext-open, ext-mid1..ext-mid5, ext-close   the words around them
  //    ext-argname         slot letter (a-f) on each operand element
  //   * priority must be the LAST constraint, and above ~250 to beat built-ins
  //   * descendant axis: the semantic tree nests children under <children>
  //   * ARG stays STRICTLY descendant (never descendant-or-self): a
  //     self-selecting [n] re-invokes speech on the same node — infinite
  //     recursion, empty output (observed 2026-08-09). The merged-operand
  //     case is handled by the dedicated intent-arity1-merged rule instead.
  var RULES_LOCALE = 'en';
  var ARG = function (n) { return './/*[@ext-argname="' + n + '"]'; };
  var PRIO = 'priority=1000';
  // While a merged operand is read (see intent-arity1-merged), SRE's grammar
  // state carries the flag intentSelf. NOT_MERGED_SELF lets the merged node
  // itself fall through to SRE's normal rules, but still speaks an arity-1
  // intent nested inside that operand (it carries no ext-argname).
  var NOT_SELF = 'not(contains(@grammar, "intentSelf"))';
  var NOT_MERGED_SELF = '(not(@ext-argname) or ' + NOT_SELF + ')';
  var RULES = {};
  RULES[RULES_LOCALE + '/rules/intent'] = {
    domain: 'clearspeak', locale: RULES_LOCALE, modality: 'speech',
    inherits: 'base',
    rules: [
      ['Rule', 'intent-arity0', 'default',
        '[t] @ext-open',
        'self::*[@ext-arity="0"]', PRIO],
      ['Rule', 'intent-arity1', 'default',
        '[t] @ext-open; [n] ' + ARG('a') + '; [t] @ext-close',
        'self::*[@ext-arity="1"]', NOT_MERGED_SELF, PRIO],
