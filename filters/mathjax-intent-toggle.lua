// ===========================================================================
//  intent-sre.js  —  MathML intent spoken by MathJax's own speech (SRE).
//
//  Stage 2 of the platform's intent rebuild (2026-11-01; the record is
//  intent-briefing/STAGE2-BRIEF.md). The converted MathML carries only the
//  MathML 4 `intent` and `arg` attributes. MathCAT (NVDA / JAWS) reads them
//  directly. SRE cannot: before its rules run it rebuilds the formula into its
//  own tree and keeps only attributes whose names start with "ext" (SRE
//  semantic_util.js, addAttributes). So, in the student's browser only, a small
//  TRANSLATOR turns each simple intent value into ext-* carriers just before
//  MathJax reads the MathML (a MathML-input filter: MathJax's documented
//  mmlFilters list), and the ClearSpeak RULES below speak those carriers. The
//  converted file itself never carries ext-*.
//
//  Words are made from the concept name [NICHOLAS 2026-11-01]: hyphens become
//  spaces, then "of" before the operands, joined by "and" (determinant($a) ->
//  "determinant of A"); :infix puts the name between the operands, :postfix
//  after them; a literal (_the-golden-ratio) is spoken as its words. Intent
//  always wins, also where SRE already reads well. Property-only, nested and
//  number-operand intents, malformed values and missing operands are left to
//  SRE's normal reading.
//
//  NOTHING here alters MathSpeak: the rules are registered for ClearSpeak
//  only, and the translator never writes ext-speech, aria-label, exact-speech
//  or alt (SRE speaks those in every style, which would override MathSpeak).
//
//  The rules reach the speech worker through installWorkerPatch (an internal
//  MathJax method; hence the pinned version). After typesetting, selfTest()
//  reports whether translated intents were really spoken.
//
//  Tests: js/test-sre-intent.mjs cuts the RULES and TRANSLATOR blocks out of
//  this file (between their START/END markers) and runs them on SRE 5.0.0-rc.4.
//
//  Since 2026-08-16 this file also remaps mhchem's Private-Use-Area reaction
//  arrows to standard Unicode in BOTH accessibility serializations (speech
//  worker payload + hidden assistive MathML) while leaving the rendered tree
//  untouched. See the CHEM ARROW REMAP section for the full rationale.
